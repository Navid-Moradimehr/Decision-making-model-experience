def phase12cE_artifact_bytes(root: Path) -> int:
    """Count only artifacts generated by this experiment, excluding archived inputs."""
    paths = [
        root / "experiments/phase12cE_execution.lock.json",
        root / "artifacts/runs/phase12cE_layout_audit_v1.json",
        root / "artifacts/runs/phase12cE_replay_parity_v1.json",
        root / "artifacts/runs/phase12cE_layout_audit_v2.json",
        root / "artifacts/runs/phase12cE_replay_parity_v2.json",
        root / "artifacts/runs/phase12cE_model_selection_v1",
        root / "artifacts/runs/phase12cE_training_v1",
        root / "artifacts/runs/phase12cE_offline_gate_v1",
        root / "artifacts/runs/phase12cE_offline_gate_result_v1.json",
    ]
    total = 0
    for path in paths:
        if path.is_file():
            total += path.stat().st_size
        elif path.is_dir():
            total += sum(item.stat().st_size for item in path.rglob("*") if item.is_file())
    return total


def verify_phase12cE_dataset_files(directory: Path) -> dict[str, Any]:
    """Verify listed file lengths/digests and exact self-inclusive artifact size."""
    manifest_path = directory / "manifest.json"
    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    for name, expected in manifest.get("files", {}).items():
        path = directory / name
        if not path.is_file():
            raise ValueError(f"dataset manifest file missing: {name}")
        raw = path.read_bytes()
        if len(raw) != int(expected["bytes"]):
            raise ValueError(f"dataset manifest byte count mismatch: {name}")
        if hashlib.sha256(raw).hexdigest().upper() != expected["sha256"]:
            raise ValueError(f"dataset manifest digest mismatch: {name}")
    actual_bytes = sum(item.stat().st_size for item in directory.iterdir() if item.is_file())
    if actual_bytes != int(manifest.get("artifact_bytes", -1)):
        raise ValueError("dataset manifest aggregate byte count mismatch")
    if len(manifest.get("files", {})) != 4:
        raise ValueError("dataset manifest does not list the four required payload files")
    return manifest


def agent_relative_state_features(states: np.ndarray) -> np.ndarray:
    """Encode goal and obstacle coordinates relative to agent, preserving all information.

    The 52-feature input order is the Phase 12 public state contract. Agent position
    remains in slots 0:2, so goal/obstacle offsets are invertible from this encoding.
    Obstacle ordering and physical constants remain unchanged.
    """
    values = np.asarray(states, dtype=np.float32)
    if values.ndim != 2 or values.shape[1] != 52 or not np.isfinite(values).all():
        raise ValueError("states must be finite [N,52] public Phase 12 features")
    relative = values.copy()
    relative[:, 6] = values[:, 6] - values[:, 0]
    relative[:, 7] = values[:, 7] - values[:, 1]
    for start in range(16, 52, 4):
        relative[:, start] = values[:, start] - values[:, 0]
        relative[:, start + 1] = values[:, start + 1] - values[:, 1]
        relative[:, start + 2] = values[:, start + 2] - values[:, 0]
        relative[:, start + 3] = values[:, start + 3] - values[:, 1]
    if not np.isfinite(relative).all():
        raise ValueError("relative state transform produced non-finite values")
    return relative


def geometry_waypoint_actions(states: np.ndarray, metadata: list[dict[str, Any]]) -> list[int]:
    """Reconstruct the frozen public-state geometry baseline, validating layout identity."""
    if len(states) != len(metadata):
        raise ValueError("state and metadata row counts differ")
    cache: dict[int, Any] = {}
    actions: list[int] = []
    for values, row in zip(states, metadata):
        seed = int(row["episode_seed"])
        scenario = cache.get(seed)
        if scenario is None:
            scenario = generate_staggered_corridor(seed)
            if scenario.layout_sha256 != row["layout_sha256"]:
                raise ValueError("metadata layout hash does not match its seed")
            cache[seed] = scenario
        spec = scenario.spec
        elapsed = int(round((1.0 - float(values[15])) * spec.max_steps))
        state = CorridorState(
            x=float(values[0]) * spec.width,
            y=float(values[1]) * spec.height,
            vx=float(values[2]) * spec.max_speed,
            vy=float(values[3]) * spec.max_speed,
            elapsed_steps=elapsed,
            status="active",
        )
        route = grid_astar_route((state.x, state.y), spec.goal, spec, resolution=0.04)
        if route is None:
            raise ValueError("geometry baseline could not route a valid state")
        actions.append(int(waypoint_braking_action(
            state, route, spec, waypoint_tolerance=0.03
        )))
    return actions


def collect_phase12_visited_balanced_dataset(
    seeds: list[int], layout_hashes: list[str], *, split: str, master_seed: int,
    suffixes_per_action: int = 14, wall_cap_seconds: int | None = None,
) -> dict[str, Any]:
    """Collect states by exact Phase-12 shooting, then independently score balanced banks.

    The Phase-12 shooting policy supplies only the closed-loop state distribution. Its
    outcomes/costs are not saved as labels. Balanced candidate landscapes are saved in
    teacher-only targets, separate from the strict student input allowlist.
    """
    if split not in {"model_selection", "offline_gate"} or len(seeds) != len(layout_hashes):
        raise ValueError("invalid split or seed/hash list")
    started = time.monotonic()
    states: list[np.ndarray] = []
    metadata: list[dict[str, Any]] = []
    episodes: list[dict[str, Any]] = []
    bank_group_keys: list[np.ndarray] = []
    bank_seeds: list[list[int]] = []
    bank_candidate_keys: list[list[np.ndarray]] = []
    bank_candidate_masks: list[list[np.ndarray]] = []
    bank_suffix_counts: list[list[int]] = []
    bank_success_available: list[list[bool]] = []
    bank_teacher_actions: list[list[int]] = []
    for seed, expected_hash in zip(seeds, layout_hashes):
        scenario = generate_staggered_corridor(int(seed))
        if scenario.layout_sha256 != expected_hash:
            raise ValueError("scenario differs from the hash-only layout audit")
        state = scenario.initial_state
        decision_index = 0
        while state.status == "active":
            if wall_cap_seconds is not None and time.monotonic() - started > wall_cap_seconds:
                raise TimeoutError("Phase 12c-E collection wall-time cap reached")
            state_row = state_features(scenario, state)
            route = grid_astar_route((state.x, state.y), scenario.spec.goal,
                                     scenario.spec, resolution=0.04)
            if route is None:
                raise ValueError("geometry waypoint route missing at a valid state")
            geometry_action = int(waypoint_braking_action(
                state, route, scenario.spec, waypoint_tolerance=0.03
            ))
            query_index = len(states)
            states.append(state_row)
            metadata.append({
                "query_index": query_index,
                "episode_seed": int(seed),
                "layout_sha256": expected_hash,
                "decision_index": decision_index,
                "source": "phase12_exact_random_shooting_closed_loop",
                "geometry_action": geometry_action,
            })
            teacher_query = make_teacher_query(scenario, state)
            teacher_action = int(teacher_query.sequences[teacher_query.selected_index, 0])
            keys_for_banks, seeds_for_banks, candidate_keys_for_banks = [], [], []
            candidate_masks_for_banks, suffix_counts_for_banks = [], []
            success_for_banks, selected_actions_for_banks = [], []
            for bank_index in range(12):
                bank_seed = derive_bank_seed(master_seed, f"phase12cE_{split}", expected_hash,
                                             decision_index, bank_index)
                bank = balanced_candidate_bank(
                    scenario, state, seed=bank_seed,
                    suffixes_per_action=suffixes_per_action,
                )
                keys_for_banks.append(bank["group_objective_keys"])
                seeds_for_banks.append(bank_seed)
                candidate_keys_for_banks.append(bank["candidate_keys"])
                candidate_masks_for_banks.append(bank["candidate_mask"])
                suffix_counts_for_banks.append(int(bank["suffix_count"]))
                success_for_banks.append(bool(bank["candidate_success_available"]))
                selected_actions_for_banks.append(int(bank["teacher_selected_action"]))
            bank_group_keys.append(np.asarray(keys_for_banks, dtype=np.float64))
            bank_seeds.append(seeds_for_banks)
            bank_candidate_keys.append(candidate_keys_for_banks)
            bank_candidate_masks.append(candidate_masks_for_banks)
            bank_suffix_counts.append(suffix_counts_for_banks)
            bank_success_available.append(success_for_banks)
            bank_teacher_actions.append(selected_actions_for_banks)
            state = corridor_step(state, teacher_action, scenario.spec).state
            decision_index += 1
        episodes.append({
            "seed": int(seed),
            "layout_sha256": expected_hash,
            "decision_queries": decision_index,
        })
    states_array = np.asarray(states, dtype=np.float32)
    keys = np.asarray(bank_group_keys, dtype=np.float64)
    targets = aggregate_bank_targets(keys)
    return {
        "inputs": {
            "states": states_array,
            "candidate_action_ids": np.broadcast_to(
                np.arange(9, dtype=np.uint8), (len(states_array), 9)
            ).copy(),
            "candidate_mask": np.ones((len(states_array), 9), dtype=np.bool_),
        },
        "targets": {
            **targets,
            "per_bank_normalized_regret": targets["per_bank_regret"],
            "per_bank_tie_split_optimal_mass": targets["per_bank_optimal_mass"],
            "train_bank_indices": np.arange(6, dtype=np.int64),
            "heldout_bank_indices": np.arange(6, 12, dtype=np.int64),
            "group_objective_keys": keys,
            "proposal_seed": np.asarray(bank_seeds, dtype=np.uint64),
            "candidate_objective_keys": np.asarray(bank_candidate_keys, dtype=np.float64),
            "candidate_objective_mask": np.asarray(bank_candidate_masks, dtype=np.bool_),
            "suffix_count": np.asarray(bank_suffix_counts, dtype=np.uint8),
            "candidate_success_available": np.asarray(bank_success_available, dtype=np.bool_),
            "teacher_selected_action": np.asarray(bank_teacher_actions, dtype=np.uint8),
        },
        "metadata": metadata,
        "episodes": episodes,
        "elapsed_wall_seconds": time.monotonic() - started,
    }


def save_phase12cE_dataset(output: Path, dataset: dict[str, Any], *, split: str,
                           config_sha256: str, execution_lock_sha256: str,
                           layout_audit_sha256: str, replay_parity_sha256: str,
                           artifact_cap_bytes: int) -> dict[str, Any]:
    """Persist split-separated inputs/targets/provenance without candidate futures."""
    if output.exists():
        raise FileExistsError(f"refusing to overwrite {output}")
    output.mkdir(parents=True, exist_ok=False)
    input_path = output / "student_inputs.npz"
    target_path = output / "teacher_targets.npz"
    metadata_path = output / "sample_metadata.json"
    episodes_path = output / "episodes.json"
    np.savez_compressed(input_path, **dataset["inputs"])
    np.savez_compressed(target_path, **dataset["targets"])
    metadata_path.write_text(json.dumps(dataset["metadata"], separators=(",", ":")) + "\n", encoding="utf-8")
    episodes_path.write_text(json.dumps(dataset["episodes"], separators=(",", ":")) + "\n", encoding="utf-8")
    files = {}
    for path in (input_path, target_path, metadata_path, episodes_path):
        raw = path.read_bytes()
        files[path.name] = {"bytes": len(raw), "sha256": hashlib.sha256(raw).hexdigest().upper()}
    manifest = {
        "schema": "phase12cE_dataset_v1",
        "phase": "12c-E",
        "split": split,
        "query_count": len(dataset["metadata"]),
        "layout_count": len(dataset["episodes"]),
        "bank_count_per_query": 12,
        "unique_bank_seeds": bool(np.unique(dataset["targets"]["proposal_seed"]).size
                                   == dataset["targets"]["proposal_seed"].size),
        "unique_query_layout_decisions": len({
            (row["layout_sha256"], row["decision_index"]) for row in dataset["metadata"]
        }) == len(dataset["metadata"]),
        "student_input_allowlist": ["states", "candidate_action_ids", "candidate_mask"],
        "teacher_targets_separate": True,
        "future_states_saved": False,
        "trajectory_policy": "phase12_exact_random_shooting_closed_loop",
        "config_sha256": config_sha256,
        "execution_lock_sha256": execution_lock_sha256,
        "layout_audit_sha256": layout_audit_sha256,
        "replay_parity_sha256": replay_parity_sha256,
        "elapsed_wall_seconds": dataset["elapsed_wall_seconds"],
        "files": files,
        "development_accessed": False,
        "dagger_accessed": False,
        "reserve_accessed": False,
        "artifact_bytes": 0,
    }
    manifest_path = output / "manifest.json"
    manifest["artifact_bytes"] = sum(x["bytes"] for x in files.values())
    for _ in range(10):
        manifest_path.write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
        actual = sum(x.stat().st_size for x in output.iterdir() if x.is_file())
        if actual == manifest["artifact_bytes"]:
            break
        manifest["artifact_bytes"] = actual
    else:
        raise RuntimeError("dataset manifest artifact-byte accounting did not converge")
    actual_bytes = sum(x.stat().st_size for x in output.iterdir() if x.is_file())
    if actual_bytes > artifact_cap_bytes:
        raise OSError("Phase 12c-E artifact cap exceeded")
    verify_phase12cE_dataset_files(output)
    return manifest
